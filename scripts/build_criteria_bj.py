def main():
    new, seen = [], defaultdict(list)
    nid = 64
    plans = plan_rows()
    # 2022~2024 복수·부전공 주전공 학점
    for it, tid, val in (("복수전공시_주전공_전공학점", "BJ-039", "39"), ("부전공시_주전공_전공학점", "BJ-040", "54")):
        plans.append(dict(years=(2022, 2024), type=by_id[tid]["이수유형"], depts=[(d, "잠정" if d in TENT22 else "확정", TENT22.get(d, "")) for d in JU22],
                          items={it: (val, "")}, tmpl={it: tid}, pagemap=PAGE22, bundle="2022~2024 다전공·부전공 제1전공 학점(건축·간호 제외)", extra={}))
    for pl in plans:
        # 같은 (상태, 사유)끼리 묶어 한 행으로
        groups = defaultdict(list)
        for d, st, why in pl["depts"]:
            groups[(st, why)].append(d)
        for (st, why), ds in groups.items():
            pages = sorted({(PAGE22 if pl["years"][0] <= 2024 and pl["years"][1] <= 2024 else PAGE25).get(d, pl["pagemap"].get(d)) for d in ds} | set(), key=int)
            pages = sorted({pl["pagemap"][d] for d in ds})
            note_extra = "; 병합 이어짐 판단: " + why if why else ""
            for item, (val, add_note) in pl["items"].items():
                tr = by_id[pl["tmpl"][item]]
                r = dict(tr)
                r["행ID"] = f"BJ-{nid:03d}"
                nid += 1
                r["입학년도_시작"], r["입학년도_끝"] = str(pl["years"][0]), str(pl["years"][1])
                r["대상단위"] = "학과"
                r["대상"] = ",".join(ds)
                r["이수유형"] = pl["type"]
                r["값"] = val
                r["값_최대"] = ""
                r["비교"] = LE.get(item, "이상") if not item.startswith("공유혁신") else "이상"
                if item == "공유혁신_전공필수":
                    r["비교"] = tr["비교"]
                r["상태"] = st
                r["확인일"] = DATE
                if pl["type"] == "단수" and pl["years"][0] >= 2025:
                    r["조건"] = ""  # 묶음 공통값 안내는 융합과정 행에만
                elif "공유혁신_전공필수" in item:
                    r["조건"] = tr["조건"]
                r["대상원어"] = ""
                pg = []
                for p in pages:
                    pg.append(f"{p}({p})")
                if pl["years"][0] <= 2024 and item.startswith("교양"):
                    pg.append("51(51)")
                r["출처쪽"] = "; ".join(dict.fromkeys(pg))
                parts = [f"E23 별지3 묶음 행({pl['bundle']}). 표 병합 셀을 PDF 이미지로 학과별로 대조해 확정(2026-11-10)", NOTE.get(item, ""), pl["extra"].get(item, ""), add_note]
                r["비고"] = "; ".join(x for x in parts if x) + note_extra
                if "교양" in item and pl["years"][0] >= 2025 and pl["type"] == "융합과정":
                    pass
                new.append(r)
                for d in ds:
                    for y in range(pl["years"][0], pl["years"][1] + 1):
                        seen[(d, y, r["이수유형"], item, r["구분"])].append(r["행ID"])
    # 기존 IT 행과 새 행 사이 충돌 검사
    for r in rows:
        if r["대학"] == "배재" and r["기준값여부"] == "기준" and r["대상"] not in ("", "전체") and r["항목"] and r["입학년도_시작"]:
            for y in range(int(r["입학년도_시작"]), int(r["입학년도_끝"] or 2028) + 1):
                for d in r["대상"].split(","):
                    k = (d, y, r["이수유형"], r["항목"], r["구분"])
                    if k in seen:
                        seen[k].append(r["행ID"])
    dup = {k: v for k, v in seen.items() if len(v) > 1}
    if dup:
        print("중복:", list(dup.items())[:10])
        sys.exit(1)
    print("새 행", len(new), "마지막", new[-1]["행ID"])
